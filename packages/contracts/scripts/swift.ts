// JSON Schema (the subset zod emits for our contracts) → Swift Codable types.
// Fails loudly on anything it doesn't understand, so a new schema feature can't silently produce wrong Swift.

type Schema = {
  type?: string;
  enum?: string[];
  properties?: Record<string, Schema>;
  required?: string[];
  additionalProperties?: boolean | Schema;
  items?: Schema;
  $ref?: string;
  allOf?: Schema[];
  description?: string;
} & Record<string, unknown>;

// Validation-only keywords: they don't change the Swift shape.
const IGNORED = new Set(["$schema", "$id", "description", "propertyNames", "minimum", "maximum", "exclusiveMinimum", "exclusiveMaximum", "minLength", "maxLength", "minItems", "maxItems"]);
const KNOWN = new Set([...IGNORED, "type", "enum", "properties", "required", "additionalProperties", "items", "$ref", "allOf"]);
const RESERVED = new Set(["default", "self", "Self", "class", "struct", "enum", "protocol", "extension", "func", "var", "let", "in", "is", "as", "init", "operator", "subscript", "import", "return", "switch", "case", "static", "super", "where", "for", "while", "if", "else", "do", "try", "throw", "true", "false", "nil", "Type", "Protocol", "Any"]);

const ident = (s: string) => (RESERVED.has(s) ? `\`${s}\`` : s);

// "skip-fit" → skipFit
const camel = (raw: string) => {
  const parts = raw.split(/[^A-Za-z0-9]+/).filter(Boolean);
  const name = parts.map((p, i) => (i === 0 ? p[0]!.toLowerCase() + p.slice(1) : p[0]!.toUpperCase() + p.slice(1))).join("");
  return /^[A-Za-z_]/.test(name) ? name : `_${name}`;
};

const refName = (ref: string) => ref.replace(/\.schema\.json$/, "");

function check(name: string, s: Schema) {
  for (const k of Object.keys(s)) if (!KNOWN.has(k)) throw new Error(`${name}: unsupported JSON Schema keyword "${k}"`);
}

function swiftType(where: string, s: Schema): string {
  check(where, s);
  // zod (draft-7) wraps a $ref that has sibling keywords as { allOf: [{ $ref }] }
  if (s.allOf) {
    if (s.allOf.length !== 1 || Object.keys(s).some((k) => k !== "allOf" && !IGNORED.has(k))) throw new Error(`${where}: unsupported allOf`);
    return swiftType(where, s.allOf[0]!);
  }
  if (s.$ref) return refName(s.$ref);
  if (s.enum) throw new Error(`${where}: inline enum — register it with def("Name", z.enum(...))`);
  switch (s.type) {
    case "string": return "String";
    case "number": return "Double";
    case "integer": return "Int";
    case "boolean": return "Bool";
    case "array":
      if (!s.items) throw new Error(`${where}: array without items`);
      return `[${swiftType(`${where}[]`, s.items)}]`;
    case "object":
      if (!s.properties && typeof s.additionalProperties === "object") {
        return `[String: ${swiftType(`${where}{}`, s.additionalProperties)}]`;
      }
      throw new Error(`${where}: inline object — register it with def("Name", z.object(...))`);
    default:
      throw new Error(`${where}: unsupported type ${JSON.stringify(s.type)}`);
  }
}

function swiftDef(name: string, s: Schema): string {
  check(name, s);
  if (s.enum) {
    const cases = s.enum.map((v) => {
      const c = camel(v);
      return `    case ${ident(c)}${c === v ? "" : ` = "${v}"`}`;
    });
    return `enum ${name}: String, Codable, Hashable, Sendable, CaseIterable {\n${cases.join("\n")}\n}`;
  }
  if (s.type === "object" && s.properties) {
    const required = new Set(s.required ?? []);
    const props = Object.entries(s.properties).map(([key, p]) => {
      if (camel(key) !== key) throw new Error(`${name}.${key}: property name must be camelCase`);
      return `    var ${ident(key)}: ${swiftType(`${name}.${key}`, p)}${required.has(key) ? "" : "?"}`;
    });
    const identifiable = s.properties.id?.type === "string" && required.has("id") ? ", Identifiable" : "";
    return `struct ${name}: Codable, Hashable, Sendable${identifiable} {\n${props.join("\n")}\n}`;
  }
  return `typealias ${name} = ${swiftType(name, s)}`;
}

export function generateSwift(schemas: Record<string, Schema>): string {
  const defs = Object.keys(schemas).sort().map((n) => swiftDef(n, schemas[n]!));
  return [
    "// Generated by packages/contracts (npm run contracts). Do not edit.",
    "// Source of truth: zod schemas in packages/contracts/src → schema/*.json → this file.",
    "",
    "import Foundation",
    "",
    defs.join("\n\n"),
    "",
  ].join("\n");
}
